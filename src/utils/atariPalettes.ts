// PAL Palette Table (adjusted hues due to PAL color burst delay)
const ATARI_PAL_RGB: [number, number, number][] = ATARI_NTSC_RGB.map(([r, g, b], idx) => {
  // PAL tint shift: slight cooler tone, higher green fidelity
  const hue = Math.floor(idx / 8);
  const lum = idx % 8;
  const factor = (lum + 1) / 8;
  if (hue === 0) return [r, g, b];
  const shiftedR = Math.min(255, Math.floor(r * 0.95 + g * 0.05));
  const shiftedG = Math.min(255, Math.floor(g * 1.05));
  const shiftedB = Math.min(255, Math.floor(b * 0.98 + (factor * 8)));
  return [shiftedR, shiftedG, shiftedB];
});

// SECAM Palette (SECAM Atari 2600 supported only 8 primary colors)
const SECAM_PRIMARIES: [number, number, number][] = [
  [0x00, 0x00, 0x00], // Black
  [0x00, 0x00, 0xff], // Blue
  [0xff, 0x00, 0x00], // Red
  [0xff, 0x00, 0xff], // Magenta
  [0x00, 0xff, 0x00], // Green
  [0x00, 0xff, 0xff], // Cyan
  [0xff, 0xff, 0x00], // Yellow
  [0xff, 0xff, 0xff], // White
];

// Helper to convert 0-255 RGB to 0-63 VGA DAC 6-bit value
export function rgb8ToDac6(val: number): number {
  return Math.min(63, Math.max(0, Math.floor((val * 63) / 255)));
}

// Convert 0-63 VGA DAC to 0-255 RGB
export function dac6ToRgb8(val: number): number {
  return Math.min(255, Math.max(0, Math.floor((val * 255) / 63)));
}

/**
 * Builds the full 256-color VGA palette for MS-DOS Mode 13h.
 * Each entry maps Atari color byte (0x00 to 0xFF) directly so in Mode 13h,
 * writing the Atari color byte directly to 0xA000 produces the exact Atari color!
 */
export function generateVgaPalette(standard: PaletteStandard): VgaColor[] {
  const palette: VgaColor[] = new Array(256);

  for (let byteVal = 0; byteVal < 256; byteVal++) {
    // Atari TIA color encoding: Upper nibble = Hue (0-15), Lower 3 bits = Lum / 2 (0-7)
    const hue = (byteVal >> 4) & 0x0F;
    const lumStep = (byteVal & 0x0E) >> 1; // Bits 3..1 (bit 0 is ignored on TIA)
    const tableIndex = hue * 8 + lumStep;

    let r8 = 0;
    let g8 = 0;
    let b8 = 0;

    switch (standard) {
      case 'NTSC': {
        const rgb = ATARI_NTSC_RGB[tableIndex] || [0, 0, 0];
        [r8, g8, b8] = rgb;
        break;
      }
      case 'PAL': {
        const rgb = ATARI_PAL_RGB[tableIndex] || [0, 0, 0];
        [r8, g8, b8] = rgb;
        break;
      }
      case 'SECAM': {
        // SECAM only uses 3 bits: 8 colors total
        const secamIdx = (byteVal >> 1) % 8;
        [r8, g8, b8] = SECAM_PRIMARIES[secamIdx];
        break;
      }
      case 'AMBER_P3': {
        // Authentic P3 amber monochrome phosphor (used in DOS CAD & terminals)
        const rgb = ATARI_NTSC_RGB[tableIndex] || [0, 0, 0];
        const luminance = 0.299 * rgb[0] + 0.587 * rgb[1] + 0.114 * rgb[2];
        const norm = luminance / 255;
        r8 = Math.min(255, Math.round(norm * 255));
        g8 = Math.min(255, Math.round(norm * 176));
        b8 = Math.min(255, Math.round(norm * 32));
        break;
      }
      case 'GREEN_P1': {
        // Authentic P1 green monochrome phosphor
        const rgb = ATARI_NTSC_RGB[tableIndex] || [0, 0, 0];
        const luminance = 0.299 * rgb[0] + 0.587 * rgb[1] + 0.114 * rgb[2];
        const norm = luminance / 255;
        r8 = Math.min(255, Math.round(norm * 40));
        g8 = Math.min(255, Math.round(norm * 255));
        b8 = Math.min(255, Math.round(norm * 48));
        break;
      }
      case 'VGA_DEFAULT':
      default: {
        // Mode 13h standard 256 color palette fallback
        if (byteVal < 16) {
          // Standard 16 CGA/EGA colors
          const cgaColors: [number, number, number][] = [
            [0x00, 0x00, 0x00], [0x00, 0x00, 0xaa], [0x00, 0xaa, 0x00], [0x00, 0xaa, 0xaa],
            [0xaa, 0x00, 0x00], [0xaa, 0x00, 0xaa], [0xaa, 0x55, 0x00], [0xaa, 0xaa, 0xaa],
            [0x55, 0x55, 0x55], [0x55, 0x55, 0xff], [0x55, 0xff, 0x55], [0x55, 0xff, 0xff],
            [0xff, 0x55, 0x55], [0xff, 0x55, 0xff], [0xff, 0xff, 0x55], [0xff, 0xff, 0xff],
          ];
          [r8, g8, b8] = cgaColors[byteVal];
        } else {
          // Map Atari NTSC for 16-255
          const rgb = ATARI_NTSC_RGB[tableIndex] || [0, 0, 0];
          [r8, g8, b8] = rgb;
        }
        break;
      }
    }

    const r6 = rgb8ToDac6(r8);
    const g6 = rgb8ToDac6(g8);
    const b6 = rgb8ToDac6(b8);

    palette[byteVal] = {
      index: byteVal,
      r6,
      g6,
      b6,
      r8: dac6ToRgb8(r6), // Canonical DAC output color
      g8: dac6ToRgb8(g6),
      b8: dac6ToRgb8(b6),
      atariHueLum: `$${hue.toString(16).toUpperCase()}${((byteVal & 0x0e)).toString(16).toUpperCase()}`
    };
  }

  return palette;
}

/**
 * Creates 768-byte binary blob suitable for streaming directly to VGA DAC port 0x3C9
 * (Port 0x3C8 write 0x00, then 768 writes of R, G, B in 6-bit format).
 */
export function getVgaDacBinaryBytes(palette: VgaColor[]): Uint8Array {
  const bytes = new Uint8Array(768);
  for (let i = 0; i < 256; i++) {
    bytes[i * 3 + 0] = palette[i].r6;
    bytes[i * 3 + 1] = palette[i].g6;
    bytes[i * 3 + 2] = palette[i].b6;
  }
  return bytes;
}
